// `xray-4d script` run as a process on the FZK-Haus sample: the plan JSON and the model sidecar (and the IFC itself) in, a script that compiles out.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { compileScript } from '../src/anim/script/compiler';
import { parseXer } from '../src/schedule/xer';
import { fromSidecar } from '../src/schedule/model';
import { linkSchedule } from '../src/schedule/link';
import { buildPlan } from '../src/schedule/plan';
import type { FourDConfig, FourDPlan } from '../src/schedule/types';

const web = resolve(__dirname, '..');
const execPath = (globalThis as unknown as { process: { execPath: string } }).process.execPath;
const cli = resolve(web, 'tools/xray-4d.mjs');
const run = (...args: string[]) => spawnSync(execPath, [cli, ...args], { cwd: web, encoding: 'utf8', timeout: 180000 });
const sidecar = resolve(web, 'public/models/fzk-haus.json');

let dir = '';
let planFile = '';
let plan: FourDPlan;
beforeAll(() => {
  const schedule = parseXer(readFileSync(resolve(web, 'public/samples/fzk-haus.xer')));
  const config = JSON.parse(readFileSync(resolve(web, 'public/samples/fzk-haus.4d.json'), 'utf8')) as FourDConfig;
  const model = fromSidecar(JSON.parse(readFileSync(sidecar, 'utf8')), { identityKey: 'fzk-sample' });
  plan = buildPlan(schedule, linkSchedule(schedule, model, config, []), model, { ...config.style, explode: 'auto' });
  dir = mkdtempSync(join(tmpdir(), 'xray4d-script-'));
  planFile = join(dir, 'fzk.4d.json');
  writeFileSync(planFile, JSON.stringify(plan));
});

const compiles = (text: string, name = 'fzk.4d.json') => compileScript(text, { plans: (n) => (n === name ? plan : null) });

describe('xray-4d script', () => {
  it('writes a script that compiles with the plan, and the notes', () => {
    const out = join(dir, 'film.xrayanim');
    const notes = join(dir, 'notes.txt');
    const r = run('script', planFile, '--model', sidecar, '-o', out, '--notes', notes);
    expect(r.status, r.stderr).toBe(0);
    expect(r.stderr).toMatch(/\d+ cues \(.*explode 2.*\), \d+ notes/);
    const text = readFileSync(out, 'utf8');
    expect(text).toMatch(/^-- generated by xray-4d script from fzk\.4d\.json \(project FZK-HAUS/);
    expect(text).toMatch(/^schedule "fzk\.4d\.json" view planned from "2027-03-01" to "2027-08-04" over 90 seconds$/m);
    const c = compiles(text);
    expect(c.errors.filter((e) => e.severity === 'error')).toEqual([]);
    expect(c.score!.cues.filter((x) => x.kind === 'caption').map((x) => (x as { title: string }).title)).toContain('Topping-out (Richtfest)');
    const n = readFileSync(notes, 'utf8').trim().split('\n');
    expect(n.length).toBeGreaterThan(10);
    expect(n.some((l) => /beat at "Topping-out/.test(l))).toBe(true);
    // deterministic
    const again = run('script', planFile, '--model', sidecar);
    expect(again.stdout).toBe(text);
  });

  it('--style, --labels, --no-explode and --no-section change the film', () => {
    const r = run('script', planFile, '--model', sidecar, '--no-explode', '--no-section', '--labels', '0', '--style', 'calm', '--name', 'film');
    expect(r.status, r.stderr).toBe(0);
    expect(r.stdout).toMatch(/^schedule "film" /m);
    expect(r.stdout).not.toMatch(/^\s*(explode|collapse|section box|label|focus) /m);
    expect(r.stdout).toMatch(/style calm, camera director, explode off, section box off, labels 0/);
    const c = compiles(r.stdout, 'film');
    expect(c.errors.filter((e) => e.severity === 'error')).toEqual([]);
  });

  it('--explode floor puts each floor apart, with the notes and a focus on the floor; a bad value is a usage error', () => {
    const r = run('script', planFile, '--model', sidecar, '--explode', 'floor');
    expect(r.status, r.stderr).toBe(0);
    expect(r.stdout).toMatch(/explode floor/);
    expect(r.stdout).toMatch(/^-- .*floor "Erdgeschoss": the work moves onto it/m);
    expect(r.stdout).toMatch(/^\s*focus where storey = "Erdgeschoss"$/m);
    expect((r.stdout.match(/^\s*explode storeys/gm) ?? []).length).toBeGreaterThanOrEqual(2);
    expect(compiles(r.stdout).errors.filter((e) => e.severity === 'error')).toEqual([]);
    expect(run('script', planFile, '--model', sidecar, '--explode', 'sideways').status).toBe(2);
  });

  it('reads the model from the IFC file too', () => {
    const r = run('script', planFile, '--model', resolve(web, '../models/AC20-FZK-Haus.ifc'));
    expect(r.status, r.stderr).toBe(0);
    expect(compiles(r.stdout).errors.filter((e) => e.severity === 'error')).toEqual([]);
  });

  it('exit codes: usage without --model or with a bad style, input for a missing or wrong file', () => {
    expect(run('script', planFile).status).toBe(2);
    expect(run('script').status).toBe(2);
    expect(run('script', planFile, '--model', sidecar, '--style', 'wild').status).toBe(2);
    expect(run('script', join(dir, 'nope.json'), '--model', sidecar).status).toBe(3);
    const bad = join(dir, 'bad.json');
    writeFileSync(bad, '{"schema":"x"}');
    const r = run('script', bad, '--model', sidecar);
    expect(r.status).toBe(3);
    expect(r.stderr).toMatch(/not a 4D plan/);
    const other = join(dir, 'other.json');
    writeFileSync(other, JSON.stringify({ elements: [{ globalId: 'zzz', ifcClass: 'IfcWall', storey: null, bounds: [0, 0, 0, 1, 1, 1] }], storeys: [] }));
    const m = run('script', planFile, '--model', other);
    expect(m.status).toBe(3);
    expect(m.stderr).toMatch(/does not match the plan/);
  });

  it('is in the help', () => {
    const r = run('script', '--help');
    expect(r.status).toBe(0);
    expect(r.stdout).toMatch(/--model/);
    expect(run('--help').stdout).toMatch(/script\s+the 4D director/);
  });
});
