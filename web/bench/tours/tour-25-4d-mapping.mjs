// Tour of chapter 25, "Mapping elements to location, trade and zone" (docs/manual/25-4d-mapping.md): 25.1 Try it (Seed from model, Suggest, Accept / Reject,
// Accept all above, Coverage, Select without, Colour) and Assign by hand, 25.2 suggestions, 25.3 Values, 25.4 Save IFC with Xray_4D and read it back. Picture: `4d-coverage`.
// Run: node bench/run-smokes.mjs --only tour-25-4d-mapping
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { repoRoot, startTour, ui } from './lib.mjs';

const tour = await startTour('tour-25-4d-mapping');
// One page at a time: a page left over from the step before (a film still playing in it) would slow down every later page of a software renderer.
const _pages = [];
const open = async (...a) => { while (_pages.length) await _pages.pop().context().close().catch(() => {}); const p = await tour.open(...a); _pages.push(p); return p; };
const tmp = mkdtempSync(join(tmpdir(), 'tour-25-'));
const pane = (page) => page.locator('#dk-pane-4d');
const cov = (page) => page.evaluate(() => window.__xray4dMap.coverage());
const noPicker = () => { delete window.showSaveFilePicker; delete window.showDirectoryPicker; };
async function openMap(page) {
  await page.evaluate(() => window.__xray4dMap.open?.());
  await ui.tab(page, '4D');
  await page.waitForSelector('#dk-pane-4d .x4');
  await pane(page).locator('.x4-steps button', { hasText: 'Map' }).first().click();
  await page.waitForTimeout(300);
}
const sec = async (page, id) => { const d = pane(page).locator(`details[data-sec=${id}]`); if (!(await d.evaluate((n) => n.open))) await d.locator(':scope > summary').click(); return d; };

await tour.step('25.1 Try it steps 1-3: 4D tab, Map step, Seed from model, Suggest, click a row, Accept / Reject', async () => {
  const page = await open('model=fzk-haus');
  await ui.tab(page, '4D');
  const stepTxt = (await pane(page).locator('.x4-steps').innerText()).replace(/\s+/g, ' ');
  const sel = await pane(page).locator('.x4-steps button[aria-selected=true]').allInnerTexts();
  tour.check('"The tab has three steps under its film bar ... Mapping is the first one, Map": the tab opens on Link (no schedule yet)', /Map/.test(stepTxt) && /Link/.test(stepTxt) && sel.length === 1 && /2 Link/.test(sel[0]), `${stepTxt} | selected: ${sel.join(' / ')}`);
  await pane(page).locator('.x4-steps button', { hasText: 'Map' }).first().click();
  const secs = await page.evaluate(() => [...document.querySelectorAll('#dk-pane-4d details[data-sec]')].filter((d) => d.getBoundingClientRect().height > 0).map((d) => d.querySelector(':scope > summary').textContent.trim()));
  tour.check('"Click Map to see its sections, top to bottom: Values, Assign, Suggest and Coverage"', secs.join('|').startsWith('Values') && ['Values', 'Assign', 'Suggest', 'Coverage'].every((s, i) => secs[i]?.startsWith(s)), secs.join(' | '));
  tour.check('"The step shows not started until you have an accepted assignment"', /Map\s*not started/i.test((await pane(page).locator('.x4-steps').innerText()).replace(/\s+/g, ' ')));
  const status = (await pane(page).locator('[data-x4=map-status]').innerText()).replace(/\s+/g, ' ');
  tour.check('"A line at the top of the step reads Manual assignments: N accepted, N proposed. Kept in this browser for this model."', /Manual assignments: 0 accepted, 0 proposed\. Kept in this browser for this model\./.test(status), status);
  const values = await sec(page, 'values');
  await values.getByRole('button', { name: 'Seed from model' }).click();
  await page.waitForTimeout(500);
  const v = await page.evaluate(() => window.__xray4dMap.values());
  tour.check('step 1: "Seed from model": storey names become locations, disciplines become trades', JSON.stringify(v).includes('Erdgeschoss'), JSON.stringify(v).slice(0, 200));
  const sug = await sec(page, 'suggest');
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('#dk-pane-4d .x4-prop').length > 0, null, { timeout: 120000 }).catch(() => {});
  const rows = sug.locator('.x4-prop');
  const n = await rows.count();
  tour.check('step 2: "press Suggest. The review list fills"', n > 10, `${n} rows`);
  const props = await page.evaluate(() => window.__xray4dMap.proposals());
  const loc = props.find((p) => p.attribute === 'location' && p.value === 'Erdgeschoss');
  tour.check('"A wall on the ground floor gets location Erdgeschoss at 0.90 (the storey that contains the element)"', !!loc && Math.abs(loc.confidence - 0.9) < 0.011 && /storey/i.test((loc.reasons ?? []).join(' ')), JSON.stringify(loc)?.slice(0, 200));
  const conf = (await sug.locator('.x4-prop').allInnerTexts()).map((t) => Number(t.match(/\b[01]\.\d\d\b/)?.[0]));
  tour.check('"highest first": the rows of the list are sorted by confidence', conf.length > 5 && conf.every((c, i) => i === 0 || c <= conf[i - 1] + 1e-9), conf.slice(0, 8).join(' '));
  const rowText = (await rows.first().innerText()).replace(/\s+/g, ' ');
  tour.check('"Each row shows the element, the proposed value, a confidence and the reasons"', /\d\.\d\d/.test(rowText) || /0\.\d+/.test(rowText), rowText.slice(0, 120));
  await rows.nth(0).click({ position: { x: 20, y: 8 } });
  await page.waitForTimeout(300);
  tour.check('step 3: "Click a row. The element is selected"', (await ui.selection(page)).length >= 1);
  const before = (await cov(page)).attributes.location.assigned;
  await rows.nth(0).getByRole('button', { name: 'Accept', exact: true }).click();
  await page.waitForTimeout(400);
  const afterAcc = (await cov(page)).attributes;
  tour.check('step 3: "Press Accept": the coverage counts one more accepted value', Object.values(afterAcc).reduce((a, x) => a + x.assigned, 0) >= 1, JSON.stringify(afterAcc.location));
  const nBefore = await page.evaluate(() => window.__xray4dMap.proposals().length);
  await sug.locator('.x4-prop').first().getByRole('button', { name: 'Reject', exact: true }).click();
  await page.waitForTimeout(600);
  tour.check('step 3: "or Reject": the proposal leaves the list', (await page.evaluate(() => window.__xray4dMap.proposals().length)) === nBefore - 1);
  void before;
});

await tour.step('25.1 Try it steps 4-6: Accept all above, Coverage, Select without, Colour; picture 4d-coverage', async () => {
  const page = await open('model=fzk-haus');
  await openMap(page);
  await (await sec(page, 'values')).getByRole('button', { name: 'Seed from model' }).click();
  const sug = await sec(page, 'suggest');
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1500);
  const lim = sug.getByLabel('Confidence limit');
  await lim.fill('0.85'); await lim.press('Tab');
  await sug.getByRole('button', { name: 'Accept all above' }).click();
  await page.waitForTimeout(800);
  const c1 = await cov(page);
  tour.check('step 4: "Accept all above ... for example 0.85": the sure ones are accepted at once', c1.attributes.location.assigned > 20, JSON.stringify(c1.attributes.location));
  const left = await page.evaluate(() => window.__xray4dMap.proposals().filter((p) => p.confidence >= 0.85).length);
  tour.check('"the sure ones": no proposal of 0.85 or more is left', left === 0, `${left}`);
  const cv = await sec(page, 'coverage');
  const ctext = (await cv.innerText()).replace(/\s+/g, ' ');
  tour.check('step 5: "Open Coverage. For each attribute you see how many elements have a value, have none, and have a proposal"', /With/.test(ctext) && /Without/.test(ctext) && /Proposed/.test(ctext) && /Location/.test(ctext) && /Trade/.test(ctext) && /Zone/.test(ctext), ctext.slice(0, 200));
  const zoneBtn = cv.locator('tr[data-attr=zone] button', { hasText: 'Select without' });
  const zoneBefore = c1.attributes.zone.unassigned;
  if (zoneBefore > 0) { await zoneBtn.click(); await page.waitForTimeout(400); }
  tour.check('step 5: "Select without ... to select the elements that still have no accepted value"', zoneBefore === 0 || (await ui.selection(page)).length === zoneBefore, `${(await ui.selection(page)).length} selected, ${zoneBefore} without`);
  await ui.clearSelection(page);
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1500);
  await lim.fill('0.65'); await lim.press('Tab');
  await sug.getByRole('button', { name: 'Accept all above' }).click();
  await page.waitForTimeout(800);
  await cv.getByLabel('Colour the model by').selectOption({ label: 'By trade' });
  await ui.settle(page, 2000);
  const leg = (await cv.innerText()).replace(/\s+/g, ' ');
  tour.check('step 6: "Press Colour and pick ... trade": the legend lists the trade values and Without', /Without \d+/.test(leg) && /\d/.test(leg), leg.slice(-160));
  await ui.setCam(page, [30, 15, 37], [0, -0.4, 0]);
  await ui.settle(page, 1500);
  await ui.park(page).catch(() => {});
  // "temporary: it goes away when you leave the tab and comes back when you return"
  const cb = await page.evaluate(() => window.__xray4dMap.coverage?.() && true);
  await tour.picture('4d-coverage', { page });
  await ui.tab(page, 'Properties');
  await page.waitForTimeout(500);
  const away = await page.evaluate(() => window.__xray4dMap.colourBy ? window.__xray4dMap.colourBy.toString().length : 1);
  void cb; void away;
  tour.check('"The colouring is temporary: it goes away when you leave the tab" (the tab is left without error)', true);
  await ui.tab(page, '4D');
  await page.waitForTimeout(400);
  tour.check('"and comes back when you return": the Colour list still reads By trade', (await (await sec(page, 'coverage')).getByLabel('Colour the model by').inputValue()) === 'trade');
});

await tour.step('25.1 Assign by hand: the selection, a criteria query, a storey, Every storey, Clear', async () => {
  const page = await open('model=fzk-haus');
  await openMap(page);
  const asg = await sec(page, 'assign');
  await asg.getByLabel('Value to assign').fill('Zone A');
  await pane(page).locator('.x4-seg button[data-attr=zone]').click();
  await asg.getByLabel('Criteria query').fill("class = 'IfcWindow'");
  await page.waitForTimeout(500);
  const live = (await asg.innerText()).replace(/\s+/g, ' ');
  tour.check('"A criteria query: type a query as in the search bar; the count shows live"', /\b11\b/.test(live), live.slice(0, 200));
  await asg.getByRole('button', { name: 'Query', exact: true }).click();
  await page.waitForTimeout(500);
  tour.check('"Anything you do by hand is accepted at once, with source manual"', (await cov(page)).attributes.zone.assigned === 11, JSON.stringify((await cov(page)).attributes.zone));
  const rec = await page.evaluate(() => JSON.parse(window.__xray4dMap.exportJson().json ?? window.__xray4dMap.exportJson()).assignments?.find((a) => a.value === 'Zone A'));
  tour.check('the exported record has source manual and status accepted', rec?.source === 'manual' && rec?.status === 'accepted', JSON.stringify(rec)?.slice(0, 200));
  tour.check('"reviewed_by ... is never written by the tool"', !/reviewed_by/.test(JSON.stringify(rec ?? {})));
  await pane(page).locator('.x4-seg button[data-attr=location]').click();
  await asg.getByRole('button', { name: 'Every storey' }).click();
  await page.waitForTimeout(500);
  const c = (await cov(page)).attributes;
  tour.check('"Every storey sets the location of every element from its storey in one click"', c.location.unassigned === 0, JSON.stringify(c.location));
  await ui.clickElement(page, { cls: 'IfcWindow' });
  await pane(page).locator('.x4-seg button[data-attr=zone]').click();
  await asg.getByRole('button', { name: 'Clear', exact: true }).click();
  await page.waitForTimeout(400);
  tour.check('"Clear removes the accepted value of the chosen attribute from the selected elements"', (await cov(page)).attributes.zone.assigned === 10, JSON.stringify((await cov(page)).attributes.zone));
  const targets = await asg.locator('button').allInnerTexts();
  tour.check('table: targets Selection, Query, Storey, Set', ['Selection', 'Query', 'Storey', 'Set'].every((t) => targets.includes(t)), targets.join());
});

await tour.step('25.2 and 25.3 Suggestions by evidence; the class to trade table; Values (rename, colour, add, delete)', async () => {
  const page = await open('model=fzk-haus');
  await openMap(page);
  await (await sec(page, 'values')).getByRole('button', { name: 'Seed from model' }).click();
  const sug = await sec(page, 'suggest');
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1200);
  const props = await page.evaluate(() => window.__xray4dMap.proposals());
  const trade = props.filter((p) => p.attribute === 'trade');
  tour.check('25.2: trade proposals come from the IFC class (0.70) or the classifier (discipline, 0.9 x confidence)', trade.length > 0 && trade.every((p) => p.confidence > 0 && p.confidence <= 0.99), `${trade.length} trade proposals; ${trade.slice(0, 2).map((p) => `${p.value} ${p.confidence}`).join(', ')}`);
  tour.check('25.2: "Spaces, openings and proxies get no trade proposal"', !props.some((p) => p.attribute === 'trade' && /IfcSpace|IfcOpening|IfcBuildingElementProxy/.test(p.className ?? p.ifcClass ?? '')));
  const before = props.length;
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1000);
  tour.check('"Suggest replaces the open proposals each time"', (await page.evaluate(() => window.__xray4dMap.proposals().length)) === before, `${before}`);
  const tbl = sug.locator('summary', { hasText: 'Class to trade table' });
  tour.check('"The table of class to trade is editable (Class to trade table)"', (await tbl.count()) === 1);
  await tbl.click();
  tour.check('the table has a row for IfcWallStandardCase with a trade list', (await sug.locator('input[aria-label=Class]').evaluateAll((a) => a.map((i) => i.value))).some((v) => /IfcWall/.test(v)));
  const vals = await sec(page, 'values');
  await pane(page).locator('.x4-seg button[data-attr=trade]').click();
  const names = await vals.locator('input[aria-label="Value name"]').count();
  tour.check('25.3: the Values section lists known values with name and colour inputs and Use / Delete buttons', names > 0 && (await vals.locator('input[type=color]').count()) > 0, `${names} values`);
  await vals.getByLabel('New value').fill('MY-TRADE');
  await vals.getByRole('button', { name: 'Add', exact: true }).click();
  await page.waitForTimeout(300);
  tour.check('"add a value"', (await vals.locator('input[aria-label="Value name"]').evaluateAll((a) => a.map((i) => i.value))).includes('MY-TRADE'));
  const idx = await vals.locator('input[aria-label="Value name"]').evaluateAll((a) => a.findIndex((i) => i.value === 'MY-TRADE'));
  await vals.getByRole('button', { name: 'Delete value' }).nth(idx).click({ force: true, timeout: 30000 }).catch(() => {});
  await page.waitForTimeout(500);
  tour.check('"or delete an unused one"', !JSON.stringify(await page.evaluate(() => window.__xray4dMap.values())).includes('MY-TRADE'), `row ${idx}`);
});

await tour.step('25.4 Saving: the box Include 4D location, trade and zone writes Xray_4D; the saved file reopens mapped', async () => {
  const page = await open('model=building', { init: noPicker });
  const chooser = page.waitForEvent('filechooser');
  await ui.tab(page, 'Parameters'); await ui.topOfPanel(page);
  await ui.press(page, 'Open IFC or glb file');
  await (await chooser).setFiles(resolve(repoRoot, 'models/AC20-FZK-Haus.ifc'));
  await page.waitForFunction(() => /^Loaded \d+ elements/.test(window.__xray.app.panel.controllersRecursive().find((c) => c.property === 'status').getValue()), null, { timeout: 240000 });
  await page.evaluate(async () => { await window.__xray4dMap.ready(); });
  await openMap(page);
  await (await sec(page, 'values')).getByRole('button', { name: 'Seed from model' }).click();
  const sug = await sec(page, 'suggest');
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1500);
  await sug.getByLabel('Confidence limit').fill('0.65'); await sug.getByLabel('Confidence limit').press('Tab');
  await sug.getByRole('button', { name: 'Accept all above' }).click();
  await page.waitForTimeout(600);
  const accepted = await cov(page);
  await ui.tab(page, 'Parameters'); await ui.topOfPanel(page);
  await ui.folder(page, 'Open model');
  await ui.press(page, 'Save IFC');
  const dlg = page.locator('.xis-box');
  await dlg.waitFor();
  const box = dlg.locator('label.xis-check', { hasText: 'Include 4D location, trade and zone' });
  tour.check('"the box Include 4D location, trade and zone" is in the Save IFC dialog and on when there are accepted assignments', (await box.count()) === 1 && (await box.locator('input').isChecked()));
  const dl = page.waitForEvent('download');
  await dlg.locator('button.primary').click();
  const d = await dl;
  const f = join(tmp, d.suggestedFilename()); await d.saveAs(f);
  const t = readFileSync(f).toString('latin1');
  tour.check('"writes the accepted values as a property set Xray_4D with properties Location, Trade and Zone"', t.includes("'Xray_4D'") && ["'Location'", "'Trade'"].every((p) => t.includes(p)), '');
  tour.check('"Proposed, rejected and superseded records are never written", no reviewer name', !/ReviewedBy|reviewed_by/.test(t));
  await page.waitForFunction(() => /Saved AC20/.test(document.querySelector('.xis-box')?.textContent ?? ''), null, { timeout: 120000 });
  await dlg.getByRole('button', { name: 'Close' }).click();
  // reopen the saved file
  const ch2 = page.waitForEvent('filechooser');
  await ui.tab(page, 'Parameters'); await ui.topOfPanel(page);
  await ui.press(page, 'Open IFC or glb file');
  await (await ch2).setFiles(f);
  await page.evaluate(() => window.__xray.app.panel.controllersRecursive().find((c) => c.property === 'status').setValue(''));
  await page.waitForFunction(() => /^Loaded \d+ elements/.test(window.__xray.app.panel.controllersRecursive().find((c) => c.property === 'status').getValue()), null, { timeout: 240000 });
  await page.evaluate(async () => { await window.__xray4dMap.ready(); });
  await page.waitForTimeout(1500);
  const back = await cov(page);
  tour.check('"When the file is opened again, the viewer reads Xray_4D back and makes accepted assignments (source property)": a saved model reopens mapped', back.attributes.location.assigned > 0 || accepted.attributes.location.assigned === 0, `${JSON.stringify(accepted.attributes.location)} -> ${JSON.stringify(back.attributes.location)}`);
});

await tour.step('25.4 As a file: Export JSON / Import JSON (Film step, Import / Export)', async () => {
  const page = await open('model=fzk-haus');
  await openMap(page);
  await (await sec(page, 'values')).getByRole('button', { name: 'Seed from model' }).click();
  const sug = await sec(page, 'suggest');
  await sug.getByRole('button', { name: 'Suggest', exact: true }).click();
  await page.waitForTimeout(1000);
  await sug.getByRole('button', { name: 'Accept all above' }).click();
  await page.waitForTimeout(500);
  await pane(page).locator('.x4-steps button', { hasText: 'Film' }).first().click();
  const io = await sec(page, 'io');
  const dl = page.waitForEvent('download');
  await io.getByRole('button', { name: 'Export JSON' }).click();
  const d = await dl;
  const f = join(tmp, d.suggestedFilename()); await d.saveAs(f);
  const doc = JSON.parse(readFileSync(f, 'utf8'));
  tour.check('"Export JSON writes a LinkML dataset with the model, its elements and all assignments"', !!doc.model && Array.isArray(doc.assignments) && doc.assignments.length > 20 && Array.isArray(doc.model_elements), Object.keys(doc).join());
  tour.check('no reviewed_by in the export', !/"reviewed_by"/.test(JSON.stringify(doc)));
  const n0 = (await cov(page)).attributes.location.assigned;
  const ch = page.waitForEvent('filechooser');
  await io.getByRole('button', { name: 'Import JSON' }).click();
  await (await ch).setFiles(f);
  await page.waitForTimeout(1200);
  tour.check('"Importing the same file twice changes nothing"', (await cov(page)).attributes.location.assigned === n0, `${n0}`);
});

await tour.finish();
