import { startTour, ui } from './lib.mjs';
import { drawThreeThings } from './views-helpers.mjs';
const tour = await startTour('tour-03-screen');
const page = await tour.open('model=fzk-haus');
page.setDefaultTimeout(60000);
await drawThreeThings(page);
await ui.tab(page, 'Views');
console.log('chips', await page.locator('#sidebar .vw-chip').allInnerTexts());
await page.locator('#sidebar .vw-chip', { hasText: /^With drawings/ }).click();
await page.waitForTimeout(800);
console.log('rows', await page.locator('#sidebar .vw-row').allInnerTexts());
const t = Date.now();
await page.locator('#sidebar .vw-row .vw-name').first().click({ timeout: 30000 }).catch((e) => console.log('row click fail', String(e).slice(0, 700)));
console.log('ms', Date.now() - t);
await page.waitForTimeout(2500);
console.log(await page.locator('#sidebar').innerText().then(t => t.replace(/\s+/g,' ').slice(0, 600)));
await tour.finish();
