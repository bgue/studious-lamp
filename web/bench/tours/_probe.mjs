import { resolve } from 'node:path';
import { startTour, ui, webRoot } from './lib.mjs';
import { drawTool } from './views-helpers.mjs';
const tour = await startTour('tour-03-screen');
const page = await tour.open('model=fzk-haus');
page.setDefaultTimeout(40000);
await ui.tab(page, 'Views');
await page.locator('#sidebar .vw-chip', { hasText: /^On sheets/ }).click();
const [fc] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: 'Open PDF' }).click()]);
await fc.setFiles(resolve(webRoot, 'public/samples/sample-sheet.pdf'));
await page.locator('#sidebar .sh-page').first().waitFor({ timeout: 60000 });
await page.locator('#sidebar .sh-page').first().click();
await page.locator('#sheet-view').waitFor({ state: 'visible' });
await page.waitForTimeout(2500);
await page.keyboard.press('0');
await page.locator('#sheet-view [data-act=draw]').click();
await page.waitForTimeout(2000);
const vis = async (l) => console.log(l, await page.evaluate(() => [...document.querySelectorAll('.markup-float')].map(e => e.style.display + ':' + e.parentElement?.id + ':' + e.getBoundingClientRect().width).join(' | ')), 'sketches', await page.evaluate(() => JSON.stringify(window.__xraySheets.sketches(window.__xraySheets.openSheet).map(s => [s.title, s.markups.map(m => m.kind)]))));
await vis('after draw click');
await drawTool(page, 'Cloud').click();
await page.waitForTimeout(1000);
await vis('after cloud tool click');
const sb = await page.locator('#sheet-view').boundingBox();
const x0 = sb.x + sb.width * 0.3, y0 = sb.y + sb.height * 0.3;
await page.mouse.move(x0, y0); await vis('hover'); await page.mouse.down(); await vis('down'); await page.mouse.move(x0 + 140, y0 + 90, { steps: 8 }); await vis('moved'); await page.mouse.up();
await page.waitForTimeout(1500);
await vis('after cloud');
await page.locator('.markup-float:visible button[data-act=done]').first().click();
await page.waitForTimeout(1500);
await vis('after done');
console.log((await page.locator('#sheet-view').innerText()).replace(/\s+/g, ' ').slice(0, 200));
await tour.finish();
