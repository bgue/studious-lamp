// `xray-4d script`: the 4D director's film as an editable .xrayanim text. Reads a plan (build.4d.json) and the model it was made
// for (an IFC file, or the sidecar .json of the node reader: the director needs element boxes, which the plan does not carry),
// runs the director (src/schedule/director.ts) and writes the script (src/schedule/directorScript.ts) with the director's notes as
// comments. The script is compiled once before it is written, so a file that does not compile is never produced.
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function makeScriptCommand({ loadParser, CliError, EXIT_OK, EXIT_USAGE, EXIT_INPUT, webRoot }) {
  const usage = (m) => new CliError(m, EXIT_USAGE);
  const input = (m) => new CliError(m, EXIT_INPUT);

  async function readModel(path) {
    if (/\.json$/i.test(path)) {
      let sidecar;
      try {
        sidecar = JSON.parse(readFileSync(path, 'utf8'));
      } catch (e) {
        throw input(`${basename(path)}: ${e.message}`);
      }
      if (!Array.isArray(sidecar.elements)) throw input(`${basename(path)}: not a model sidecar (no elements)`);
      return sidecar;
    }
    const { convertIfcFiles } = await import(pathToFileURL(join(webRoot, 'tools', 'pack', 'convert.mjs')).href);
    try {
      return (await convertIfcFiles([{ name: basename(path), bytes: new Uint8Array(readFileSync(path)) }])).sidecar;
    } catch (e) {
      throw input(`${basename(path)}: ${e.message}`);
    }
  }

  async function run(args, io) {
    const file = args._[0];
    if (!file) throw usage('script needs a plan file: xray-4d script build.4d.json --model model.ifc -o film.xrayanim');
    if (args._.length > 1) throw usage(`script takes one plan file, got ${args._.length}`);
    if (!args.model) throw usage('script needs --model model.ifc (the director needs the element boxes, which the plan does not carry; a sidecar .json of the IFC reader also works)');
    if (args.style !== undefined && !['calm', 'dynamic'].includes(args.style)) throw usage(`--style is calm or dynamic, got "${args.style}"`);
    const planPath = resolve(file);
    const modelPath = resolve(args.model);
    for (const p of [planPath, modelPath]) if (!existsSync(p) || !statSync(p).isFile()) throw input(`cannot read ${p === planPath ? file : args.model}`);
    let plan;
    try {
      plan = JSON.parse(readFileSync(planPath, 'utf8'));
    } catch (e) {
      throw input(`${basename(file)}: ${e.message}`);
    }
    if (plan?.schema !== 'xray-4d-plan/1' || !Array.isArray(plan.elements)) throw input(`${basename(file)}: not a 4D plan (schema xray-4d-plan/1)`);

    const parser = await loadParser();
    const sidecar = await readModel(modelPath);
    const model = parser.fromSidecar(sidecar, { name: basename(modelPath) });
    const known = new Set(model.elements.filter((e) => e.bbox).map((e) => e.globalId));
    const found = plan.elements.filter((e) => known.has(e.globalId)).length;
    if (plan.elements.length > 0 && found * 2 < plan.elements.length) throw input(`the model does not match the plan: only ${found} of its ${plan.elements.length} elements are in ${basename(modelPath)}`);
    if (found < plan.elements.length) io.err(`xray-4d: ${plan.elements.length - found} of ${plan.elements.length} planned elements are not in the model (left out of the framing)`);

    const style = { ...plan.style };
    if (args.explode && !['auto', 'floor', 'off'].includes(args.explode)) throw usage(`--explode is auto, floor or off, got "${args.explode}"`);
    if (args.explode) style.explode = args.explode;
    if (args.fade !== undefined) {
      const v = Number(String(args.fade).replace(/s$/i, ''));
      if (!Number.isFinite(v) || v < 0) throw usage(`--fade needs seconds (0 = at once), got "${args.fade}"`);
      style.fadeIn = v;
    }
    if (args['no-explode']) style.explode = 'off';
    if (args['no-section']) style.sectionBox = 'off';
    if (args.labels !== undefined) style.labels = args.labels;
    plan = { ...plan, style };
    const result = parser.directFourD(plan, model, { profile: args.style ?? 'dynamic' });
    const planName = args.name ?? basename(file);
    const header = [
      `generated by xray-4d script from ${basename(file)} (project ${plan.schedule?.project ?? '?'}${plan.schedule?.dataDate ? `, data date ${plan.schedule.dataDate}` : ''}), model ${basename(modelPath)}; edit freely`,
      `style ${args.style ?? 'dynamic'}, camera ${style.camera}, explode ${style.explode}, section box ${style.sectionBox}, labels ${style.labels}. The notes before each block say why the director did it.`,
    ];
    const text = parser.scriptFromPlan(plan, result, { planName, header });
    const check = parser.compileScript(text, { plans: (n) => (n === planName ? plan : null) });
    const errors = check.errors.filter((e) => e.severity === 'error');
    if (errors.length > 0) throw new CliError(`the generated script does not compile (line ${errors[0].line}: ${errors[0].message})`, 1);

    if (args.out) writeFileSync(resolve(args.out), text);
    else io.out(text.replace(/\n$/, ''));
    if (args.notes) writeFileSync(resolve(args.notes), `${result.notes.join('\n')}\n`);
    const kinds = {};
    for (const c of result.cues) kinds[c.kind] = (kinds[c.kind] ?? 0) + 1;
    io.err(`xray-4d: ${result.cues.length} cues (${Object.entries(kinds).map(([k, n]) => `${k} ${n}`).join(', ')}), ${result.notes.length} notes${args.out ? ` -> ${args.out}` : ''}`);
    return EXIT_OK;
  }

  return {
    summary: 'the 4D director: a camera, explode, section box, caption and label script (.xrayanim) from a plan and its model',
    usage: 'xray-4d script <build.4d.json> --model <model.ifc|sidecar.json> [--style calm|dynamic] [--labels N] [--explode auto|floor|off] [--fade S] [--no-explode] [--no-section] [--name NAME] -o film.xrayanim [--notes notes.txt]',
    options: { '--model': 'string', '--style': 'string', '--labels': 'int', '--explode': 'string', '--fade': 'string', '--no-explode': 'bool', '--no-section': 'bool', '--name': 'string', '--out': 'string', '--notes': 'string' },
    optionHelp: [
      '  --model FILE     the model the plan was made for: an IFC file, or the sidecar .json of the IFC reader (element boxes and storeys)',
      '  --style S        calm (6 s shots, slower moves) or dynamic (4 s shots; default)',
      '  --labels N       at most N activity labels at once (0 = none; default: the plan\'s style)',
      '  --explode E      auto (default), floor (each floor apart while it is built) or off',
      '  --fade S         seconds a new part takes to fade in (the schedule line gets `fade S seconds`)',
      '  --no-explode     no explode, collapse or milestone beats',
      '  --no-section     no section boxes',
      '  --name NAME      the plan name written in the script\'s schedule statement (default: the plan file name); register the plan under it',
      '  -o, --out FILE   write the script here (default: standard output)',
      '  --notes FILE     also write the director\'s notes (one line per decision, with time and date) to a text file',
    ],
    run,
  };
}
