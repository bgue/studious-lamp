CREATE OR REPLACE VIEW v_cost_cost_code AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.code AS code,
  t.parent_code AS parent_code,
  t.level AS level,
  t.uom AS uom,
  t.is_active AS is_active,
  t.snapshot_id AS snapshot_id,
  t.period AS period,
  t.as_of AS as_of,
  t.hours_budget AS hours_budget,
  t.hours_actual AS hours_actual,
  t.hours_earned AS hours_earned,
  t.hours_ftc AS hours_ftc,
  t.hours_eac AS hours_eac,
  t.quantity_budget AS quantity_budget,
  t.quantity_actual AS quantity_actual,
  t.quantity_earned AS quantity_earned,
  t.quantity_ftc AS quantity_ftc,
  t.quantity_eac AS quantity_eac,
  t.amount_budget AS amount_budget,
  t.amount_actual AS amount_actual,
  t.amount_earned AS amount_earned,
  t.amount_ftc AS amount_ftc,
  t.amount_eac AS amount_eac
FROM cur_cost_costcode AS t
JOIN cur_core_record AS r ON r.id = t.id;
