CREATE OR REPLACE VIEW v_quality_inspection AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.subject_id AS subject_id,
  t.for_iwp_id AS for_iwp_id,
  t.checklist_id AS checklist_id,
  t.checklist_version AS checklist_version,
  t.point AS point,
  t.area AS area,
  t.planned_on AS planned_on,
  t.scheduled_for AS scheduled_for,
  t.inspector AS inspector,
  t.result AS result,
  t.done_at AS done_at,
  t.answers_json AS answers_json,
  t.note AS note,
  t.recorded_by AS recorded_by,
  t.verified_by AS verified_by,
  t.verified_on AS verified_on,
  t.reinspection_of_id AS reinspection_of_id,
  t.cancel_reason AS cancel_reason,
  t.punch_count AS punch_count
FROM cur_quality_inspection AS t
JOIN cur_core_record AS r ON r.id = t.id;
