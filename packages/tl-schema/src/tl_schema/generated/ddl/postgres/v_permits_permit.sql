CREATE OR REPLACE VIEW v_permits_permit AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.permit_type AS permit_type,
  t.for_record_id AS for_record_id,
  t.area AS area,
  t.location_text AS location_text,
  t.holder AS holder,
  t.requested_by AS requested_by,
  t.needed_from AS needed_from,
  t.needed_until AS needed_until,
  t.approved_by AS approved_by,
  t.issued_by AS issued_by,
  t.issued_at AS issued_at,
  t.valid_until AS valid_until,
  t.precautions_json AS precautions_json,
  t.revalidation_count AS revalidation_count,
  t.last_revalidated_at AS last_revalidated_at,
  t.suspend_reason AS suspend_reason,
  t.handback_note AS handback_note,
  t.closed_by AS closed_by,
  t.reject_reason AS reject_reason,
  t.cancel_reason AS cancel_reason,
  t.lapse_flagged_for AS lapse_flagged_for
FROM cur_permits_permit AS t
JOIN cur_core_record AS r ON r.id = t.id;
