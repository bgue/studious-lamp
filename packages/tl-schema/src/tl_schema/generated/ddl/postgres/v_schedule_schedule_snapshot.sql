CREATE OR REPLACE VIEW v_schedule_schedule_snapshot AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.schedule_id AS schedule_id,
  t.schedule_code AS schedule_code,
  t.number AS number,
  t.p6_project_option AS p6_project_option,
  t.source_file_id AS source_file_id,
  t.source_name AS source_name,
  t.source_sha256 AS source_sha256,
  t.source_size AS source_size,
  t.requested_by AS requested_by,
  t.attempts AS attempts,
  t.last_error AS last_error,
  t.data_date AS data_date,
  t.p6_version AS p6_version,
  t.p6_project AS p6_project,
  t.activity_count AS activity_count,
  t.relationship_count AS relationship_count,
  t.wbs_count AS wbs_count,
  t.calendar_count AS calendar_count,
  t.code_count AS code_count,
  t.udf_count AS udf_count,
  t.error_count AS error_count,
  t.warning_count AS warning_count,
  t.report_file_id AS report_file_id,
  t.raw_file_id AS raw_file_id,
  t.typed_sha256 AS typed_sha256,
  t.raw_sha256 AS raw_sha256,
  t.built_at AS built_at,
  t.published_at AS published_at
FROM cur_schedule_schedule_snapshot AS t
JOIN cur_core_record AS r ON r.id = t.id;
