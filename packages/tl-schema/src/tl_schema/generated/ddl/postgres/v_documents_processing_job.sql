CREATE OR REPLACE VIEW v_documents_processing_job AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.kind AS kind,
  t.derived_id AS derived_id,
  t.derived_key AS derived_key,
  t.source_ref AS source_ref,
  t.source_file_id AS source_file_id,
  t.extractor AS extractor,
  t.options_json AS options_json,
  t.schema_id AS schema_id,
  t.requested_by AS requested_by,
  t.state AS state,
  t.attempt AS attempt,
  t.max_attempts AS max_attempts,
  t.worker AS worker,
  t.started_at AS started_at,
  t.finished_at AS finished_at,
  t.error_code AS error_code,
  t.error_message AS error_message,
  t.result_json AS result_json,
  t.created_seq AS created_seq
FROM cur_documents_processing_job AS t
JOIN cur_core_record AS r ON r.id = t.id;
