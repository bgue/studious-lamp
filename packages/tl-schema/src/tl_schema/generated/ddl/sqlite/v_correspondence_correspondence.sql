CREATE VIEW IF NOT EXISTS v_correspondence_correspondence AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.number AS number,
  t.direction AS direction,
  t.medium AS medium,
  t.received_via AS received_via,
  t.external_ref AS external_ref,
  t.message_id AS message_id,
  t.in_reply_to AS in_reply_to,
  t.from_party_id AS from_party_id,
  t.from_name AS from_name,
  t.to_json_json AS to_json_json,
  t.cc_json_json AS cc_json_json,
  t.sent_on AS sent_on,
  t.received_on AS received_on,
  t.issued_on AS issued_on,
  t.body AS body,
  t.confidentiality AS confidentiality,
  t.domain AS domain,
  t.subtype AS subtype,
  t.thread_id AS thread_id,
  t.responds_to_id AS responds_to_id,
  t.superseded_by_id AS superseded_by_id,
  t.response_required AS response_required,
  t.response_due AS response_due,
  t.responded_on AS responded_on,
  t.triaged_on AS triaged_on,
  t.triaged_by AS triaged_by,
  t.rendition_file_id AS rendition_file_id,
  t.rendition_sha256 AS rendition_sha256,
  t.delivery AS delivery
FROM cur_correspondence_correspondence AS t
JOIN cur_core_record AS r ON r.id = t.id;
