CREATE VIEW IF NOT EXISTS v_correspondence_response_clock AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.item_id AS item_id,
  t.item_number AS item_number,
  t.label AS label,
  t.kind AS kind,
  t.start_on AS start_on,
  t.duration_days AS duration_days,
  t.day_type AS day_type,
  t.calendar AS calendar,
  t.warn_days_json AS warn_days_json,
  t.due_on AS due_on,
  t.state AS state,
  t.paused_on AS paused_on,
  t.pause_reason AS pause_reason,
  t.closed_on AS closed_on,
  t.closed_reason AS closed_reason,
  t.warned_level AS warned_level,
  t.owner AS owner,
  t.clause_id AS clause_id,
  t.restarts AS restarts
FROM cur_correspondence_response_clock AS t
JOIN cur_core_record AS r ON r.id = t.id;
