CREATE VIEW IF NOT EXISTS v_schemareg_schema_package AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.package AS package,
  t.semver AS semver,
  t.kind AS kind,
  t.project AS project,
  t.package_title AS package_title,
  t.content AS content,
  t.content_sha256 AS content_sha256,
  t.changelog AS changelog,
  t.drafted_by AS drafted_by,
  t.base_ref AS base_ref,
  t.classification AS classification,
  t.classification_digest AS classification_digest,
  t.worst_class AS worst_class,
  t.impact AS impact,
  t.impact_sha256 AS impact_sha256,
  t.analysed_sha256 AS analysed_sha256,
  t.submitted_by AS submitted_by,
  t.approved_by AS approved_by,
  t.approved_digest AS approved_digest,
  t.published_at AS published_at,
  t.deprecated_at AS deprecated_at,
  t.retired_at AS retired_at
FROM cur_schemareg_schema_package AS t
JOIN cur_core_record AS r ON r.id = t.id;
