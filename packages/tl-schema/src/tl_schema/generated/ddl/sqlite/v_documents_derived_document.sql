CREATE VIEW IF NOT EXISTS v_documents_derived_document AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.source_document_id AS source_document_id,
  t.source_revision_id AS source_revision_id,
  t.source_document_number AS source_document_number,
  t.source_revision_code AS source_revision_code,
  t.source_ref AS source_ref,
  t.schema_id AS schema_id,
  t.schema_code AS schema_code,
  t.schema_version AS schema_version,
  t.method AS method,
  t.previous_derived_id AS previous_derived_id,
  t.content_rev AS content_rev,
  t.published_rev AS published_rev,
  t.validation_status AS validation_status,
  t.row_count AS row_count,
  t.error_count AS error_count,
  t.published_correlation_id AS published_correlation_id,
  t.published_at AS published_at,
  t.published_count AS published_count,
  t.last_job_id AS last_job_id
FROM cur_documents_derived_document AS t
JOIN cur_core_record AS r ON r.id = t.id;
