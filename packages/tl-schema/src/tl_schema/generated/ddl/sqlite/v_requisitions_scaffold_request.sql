CREATE VIEW IF NOT EXISTS v_requisitions_scaffold_request AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.purpose AS purpose,
  t.elevation AS elevation,
  t.gridline AS gridline,
  t.length_m AS length_m,
  t.width_m AS width_m,
  t.height_m AS height_m,
  t.load_class AS load_class,
  t.duration_days AS duration_days,
  t.kind AS kind,
  t.subject AS subject,
  t.requester AS requester,
  t.need_by AS need_by,
  t.location_text AS location_text,
  t.priority AS priority,
  t.for_record_id AS for_record_id,
  t.approved_by AS approved_by,
  t.approved_at AS approved_at,
  t.reject_reason AS reject_reason,
  t.work_order_id AS work_order_id
FROM cur_requisitions_scaffold_request AS t
JOIN cur_core_record AS r ON r.id = t.id;
