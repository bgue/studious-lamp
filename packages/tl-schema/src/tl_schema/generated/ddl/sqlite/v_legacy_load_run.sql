CREATE VIEW IF NOT EXISTS v_legacy_load_run AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.source_system AS source_system,
  t.source_table AS source_table,
  t.run_number AS run_number,
  t.loader AS loader,
  t.source_name AS source_name,
  t.source_sha256 AS source_sha256,
  t.source_size AS source_size,
  t.row_count AS row_count,
  t.column_count AS column_count,
  t.extracted_file_id AS extracted_file_id,
  t.extracted_sha256 AS extracted_sha256,
  t.profile_file_id AS profile_file_id,
  t.profile_sha256 AS profile_sha256,
  t.bronze_rows AS bronze_rows,
  t.mapping_name AS mapping_name,
  t.mapping_sha256 AS mapping_sha256,
  t.plan_new AS plan_new,
  t.plan_existing AS plan_existing,
  t.plan_invalid AS plan_invalid,
  t.loaded_count AS loaded_count,
  t.record_ids AS record_ids,
  t.correlation_id AS correlation_id,
  t.report_file_id AS report_file_id,
  t.report_sha256 AS report_sha256,
  t.report_document_id AS report_document_id,
  t.mismatches AS mismatches,
  t.opened_by AS opened_by,
  t.last_error AS last_error
FROM cur_legacy_load_run AS t
JOIN cur_core_record AS r ON r.id = t.id;
