CREATE VIEW IF NOT EXISTS v_engineering_code_value AS
SELECT
  r.id AS id,
  r.key AS key,
  r.type AS record_type,
  r.scope AS scope,
  r.title AS title,
  r.description AS description,
  r.status AS status,
  r.voided AS voided,
  r.version AS version,
  r.conformance AS conformance,
  r.psets_json AS psets_json,
  r.created_at AS created_at,
  r.updated_at AS updated_at,
  t.code_list AS code_list,
  t.code AS code,
  t.label AS label,
  t.meaning AS meaning,
  t.crosswalk AS crosswalk,
  t.origin AS origin,
  t.sort_order AS sort_order,
  t.effective_from AS effective_from,
  t.effective_to AS effective_to,
  t.lifecycle AS lifecycle,
  t.superseded_by AS superseded_by,
  t.attributes_json AS attributes_json,
  t.edition AS edition
FROM cur_engineering_code_value AS t
JOIN cur_core_record AS r ON r.id = t.id;
