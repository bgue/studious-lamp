#!/usr/bin/env bash
# Build /home/user/xray-ref-dist/xray-ref.zip:
#   - the whole repo minus web/node_modules, web/dist, web/dist-single, web/.single-build, models-probe, .git,
#     __pycache__ and *.png larger than 2 MB;
#   - the single-file viewer at the zip root as xray-viewer.html (built with `npm run bundle` if missing or stale);
#   - web/public/models/*.glb and *.json (always, including synth5k, which is not embedded in the viewer).
# Usage: bash tools/make_zip.sh [output.zip]
# Uses Python's zipfile (the `zip` CLI is not required).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-/home/user/xray-ref-dist/xray-ref.zip}"
SINGLE="$REPO/web/dist-single/xray-viewer.html"

if [ ! -f "$SINGLE" ] || [ -n "$(find "$REPO/web/src" "$REPO/web/index.html" "$REPO/web/tools" "$REPO/web/public" -newer "$SINGLE" -type f 2>/dev/null | head -n 1)" ]; then
  echo "building the single-file viewer (npm run bundle)..."
  (cd "$REPO/web" && npm run bundle >/dev/null)
fi
[ -f "$SINGLE" ] || { echo "missing $SINGLE" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
rm -f "$OUT"

python3 -I - "$REPO" "$OUT" "$SINGLE" <<'PY'
import os, sys, zipfile

repo, out, single = sys.argv[1:4]
PNG_LIMIT = 2 * 1024 * 1024
EXCLUDE_DIRS = {'.git', '__pycache__', 'node_modules'}
KEEP_BENCH_PNG = {'app-building.png', 'app-synth5k.png', 'smoke-scope-all.png', 'ghost-after-all-0.15.png', 'explode-storeys.png', 'help-tooltip.png', 'smoke-dock-closed.png', 'oit-oblique-reversed-on.png', 'oit-oblique-reversed-off.png', 'layers-front.png'}
EXCLUDE_PATHS = {'web/node_modules', 'web/dist', 'web/dist-single', 'web/.single-build', 'models-probe'}

added = {}
skipped_png = []

def add(zf, path, arc):
    if arc in added:
        return
    zf.write(path, arc)
    added[arc] = os.path.getsize(path)

with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
    for dirpath, dirnames, filenames in os.walk(repo):
        rel_dir = os.path.relpath(dirpath, repo).replace(os.sep, '/')
        rel_dir = '' if rel_dir == '.' else rel_dir
        dirnames[:] = sorted(d for d in dirnames
                             if d not in EXCLUDE_DIRS and (rel_dir + '/' + d).lstrip('/') not in EXCLUDE_PATHS)
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            arc = (rel_dir + '/' + fn).lstrip('/')
            # Benchmark screenshots are regenerated by the bench scripts; keep only a small curated set.
            if rel_dir.replace(os.sep, '/').startswith('web/bench') and fn.lower().endswith('.png') and fn not in KEEP_BENCH_PNG:
                skipped_png.append(arc)
                continue
            if fn.lower().endswith('.png') and os.path.getsize(full) > PNG_LIMIT:
                skipped_png.append(arc)
                continue
            if fn.endswith('.pyc'):
                continue
            add(zf, full, arc)
    add(zf, single, 'xray-viewer.html')
    models = os.path.join(repo, 'web', 'public', 'models')
    for fn in sorted(os.listdir(models)):
        if fn.endswith('.glb') or fn.endswith('.json'):
            add(zf, os.path.join(models, fn), 'web/public/models/' + fn)

size = os.path.getsize(out)
print(f'zip: {out}')
print(f'size: {size} bytes ({size / 1048576:.2f} MB), files: {len(added)}, uncompressed: {sum(added.values()) / 1048576:.2f} MB')
print(f'skipped png > 2 MB: {len(skipped_png)}' + (' (' + ', '.join(skipped_png) + ')' if skipped_png else ''))
PY
